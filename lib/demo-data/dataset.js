export const DEMO_DOMAIN = "demo.velocityturf.internal";
export const DEMO_TAG = "[DEMO]";

export function isDemoEmail(email) {
  return typeof email === "string" && email.endsWith(`@${DEMO_DOMAIN}`);
}

export function isDemoRecord(record) {
  if (!record) return false;
  if (record.is_demo === true) return true;
  if (typeof record.email === "string" && isDemoEmail(record.email)) return true;
  if (typeof record.name === "string" && record.name.includes(DEMO_TAG)) return true;
  if (typeof record.title === "string" && record.title.includes(DEMO_TAG)) return true;
  if (typeof record.note === "string" && record.note.includes(DEMO_TAG)) return true;
  if (typeof record.text === "string" && record.text.includes(DEMO_TAG)) return true;
  if (typeof record.issue === "string" && record.issue.includes(DEMO_TAG)) return true;
  if (typeof record.ticket_number === "string" && record.ticket_number.startsWith("DEMO-")) return true;
  if (typeof record.payout_number === "string" && record.payout_number.startsWith("DEMO-")) return true;
  if (Array.isArray(record.amenities) && record.amenities.includes("Demo")) return true;
  return false;
}

export function formatDemoName(name = "") {
  if (typeof name !== "string") return { clean: name, isDemo: false };
  const isDemo = name.includes(DEMO_TAG);
  const clean = name.replace(/\[DEMO\]/g, "").replace(/\s+/g, " ").trim();
  return { clean, isDemo };
}

